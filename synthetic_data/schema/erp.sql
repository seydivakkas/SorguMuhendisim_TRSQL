-- TRSQL Sentetik Kurumsal ERP / Satış / Finans / Stok / İK Şeması (PostgreSQL 16)
-- Tüm değerler ve varlıklar %100 sentetiktir; gerçek kişisel veri içermez.
-- Türkçe sıralama ve büyük/küçük harf duyarlılığı için PG16 ICU "tr-TR-x-icu" kullanılır.
-- Çapraz dilli şema eşlemeyi (cross-lingual schema linking) ölçmek amacıyla
-- son 4 tablo kasıtlı olarak İngilizce kısaltmalı adlarla (cust_loyalty, inv_ledger, vb.) tanımlanmıştır.

CREATE TABLE IF NOT EXISTS bolgeler (
    bolge_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bolge_kodu TEXT NOT NULL UNIQUE,
    bolge_adi  TEXT COLLATE "tr-TR-x-icu" NOT NULL,
    ulke       TEXT COLLATE "tr-TR-x-icu" NOT NULL DEFAULT 'Türkiye'
);

CREATE TABLE IF NOT EXISTS bayiler (
    bayi_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bolge_id      INTEGER NOT NULL REFERENCES bolgeler (bolge_id),
    bayi_kodu     TEXT NOT NULL UNIQUE,
    bayi_adi      TEXT COLLATE "tr-TR-x-icu" NOT NULL,
    sehir         TEXT COLLATE "tr-TR-x-icu" NOT NULL,
    ilce          TEXT COLLATE "tr-TR-x-icu" NOT NULL,
    vergi_no      TEXT NOT NULL, -- Hassas / sahte (RBAC reddedilen sütun adayı)
    telefon       TEXT NOT NULL,
    eposta        TEXT NOT NULL,
    aktif         BOOLEAN NOT NULL DEFAULT TRUE,
    acilis_tarihi DATE NOT NULL,
    tenant_id     TEXT NOT NULL DEFAULT 't-kurum'
);

CREATE TABLE IF NOT EXISTS musteri_segmentleri (
    segment_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    segment_adi   TEXT COLLATE "tr-TR-x-icu" NOT NULL UNIQUE,
    indirim_orani NUMERIC(5, 2) NOT NULL DEFAULT 0,
    min_ciro      NUMERIC(14, 2) NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS musteriler (
    musteri_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    segment_id           INTEGER NOT NULL REFERENCES musteri_segmentleri (segment_id),
    bayi_id              INTEGER NOT NULL REFERENCES bayiler (bayi_id),
    ad_soyad             TEXT COLLATE "tr-TR-x-icu" NOT NULL,
    unvan                TEXT COLLATE "tr-TR-x-icu" NOT NULL,
    sehir                TEXT COLLATE "tr-TR-x-icu" NOT NULL,
    tckn                 TEXT NOT NULL, -- Hassas / sahte (biçimsel olarak geçersiz 00...)
    telefon              TEXT NOT NULL,
    eposta               TEXT NOT NULL,
    kayit_tarihi         DATE NOT NULL,
    son_alisveris_tarihi DATE,
    aktif                BOOLEAN NOT NULL DEFAULT TRUE,
    kredi_limiti         NUMERIC(14, 2) NOT NULL DEFAULT 0,
    tenant_id            TEXT NOT NULL DEFAULT 't-kurum'
);

CREATE TABLE IF NOT EXISTS kategoriler (
    kategori_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ust_kategori_id INTEGER REFERENCES kategoriler (kategori_id),
    kategori_adi    TEXT COLLATE "tr-TR-x-icu" NOT NULL UNIQUE,
    kdv_orani       NUMERIC(5, 2) NOT NULL DEFAULT 20.00
);

CREATE TABLE IF NOT EXISTS urunler (
    urun_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kategori_id    INTEGER NOT NULL REFERENCES kategoriler (kategori_id),
    urun_kodu      TEXT NOT NULL UNIQUE,
    urun_adi       TEXT COLLATE "tr-TR-x-icu" NOT NULL,
    birim          TEXT COLLATE "tr-TR-x-icu" NOT NULL DEFAULT 'Adet',
    birim_fiyat    NUMERIC(12, 2) NOT NULL,
    maliyet_fiyati NUMERIC(12, 2) NOT NULL,
    kdv_orani      NUMERIC(5, 2) NOT NULL DEFAULT 20.00,
    aktif          BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS depolar (
    depo_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bolge_id  INTEGER NOT NULL REFERENCES bolgeler (bolge_id),
    depo_kodu TEXT NOT NULL UNIQUE,
    depo_adi  TEXT COLLATE "tr-TR-x-icu" NOT NULL,
    sehir     TEXT COLLATE "tr-TR-x-icu" NOT NULL,
    kapasite  INTEGER NOT NULL CHECK (kapasite > 0),
    aktif     BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS stok_hareketleri (
    hareket_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    depo_id        INTEGER NOT NULL REFERENCES depolar (depo_id),
    urun_id        INTEGER NOT NULL REFERENCES urunler (urun_id),
    hareket_turu   TEXT NOT NULL CHECK (hareket_turu IN ('giris', 'cikis', 'transfer', 'iade')),
    miktar         INTEGER NOT NULL,
    hareket_tarihi DATE NOT NULL,
    aciklama       TEXT COLLATE "tr-TR-x-icu" NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS kampanyalar (
    kampanya_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kampanya_adi     TEXT COLLATE "tr-TR-x-icu" NOT NULL,
    baslangic_tarihi DATE NOT NULL,
    bitis_tarihi     DATE NOT NULL,
    indirim_yuzdesi  NUMERIC(5, 2) NOT NULL DEFAULT 0,
    aktif            BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS departmanlar (
    departman_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departman_adi TEXT COLLATE "tr-TR-x-icu" NOT NULL UNIQUE,
    butce         NUMERIC(14, 2) NOT NULL
);

CREATE TABLE IF NOT EXISTS calisanlar (
    calisan_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departman_id     INTEGER NOT NULL REFERENCES departmanlar (departman_id),
    bayi_id          INTEGER NOT NULL REFERENCES bayiler (bayi_id),
    ad_soyad         TEXT COLLATE "tr-TR-x-icu" NOT NULL,
    unvan            TEXT COLLATE "tr-TR-x-icu" NOT NULL,
    sehir            TEXT COLLATE "tr-TR-x-icu" NOT NULL,
    tckn             TEXT NOT NULL, -- Hassas / sahte
    ise_giris_tarihi DATE NOT NULL,
    aktif            BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS siparisler (
    siparis_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    musteri_id     INTEGER NOT NULL REFERENCES musteriler (musteri_id),
    bayi_id        INTEGER NOT NULL REFERENCES bayiler (bayi_id),
    calisan_id     INTEGER NOT NULL REFERENCES calisanlar (calisan_id),
    kampanya_id    INTEGER REFERENCES kampanyalar (kampanya_id),
    siparis_no     TEXT NOT NULL UNIQUE,
    siparis_tarihi DATE NOT NULL,
    durum          TEXT NOT NULL CHECK (durum IN ('tamamlandi', 'beklemede', 'kargoda', 'iptal')),
    odeme_yontemi  TEXT COLLATE "tr-TR-x-icu" NOT NULL CHECK (odeme_yontemi IN ('Kredi Kartı', 'Havale', 'Vadeli')),
    brut_tutar     NUMERIC(14, 2) NOT NULL,
    indirim_tutari NUMERIC(14, 2) NOT NULL DEFAULT 0,
    kdv_tutari     NUMERIC(14, 2) NOT NULL DEFAULT 0,
    toplam_tutar   NUMERIC(14, 2) NOT NULL,
    iade_tutari    NUMERIC(14, 2) NOT NULL DEFAULT 0,
    tenant_id      TEXT NOT NULL DEFAULT 't-kurum'
);

CREATE TABLE IF NOT EXISTS siparis_kalemleri (
    kalem_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    siparis_id     INTEGER NOT NULL REFERENCES siparisler (siparis_id),
    urun_id        INTEGER NOT NULL REFERENCES urunler (urun_id),
    miktar         INTEGER NOT NULL CHECK (miktar > 0),
    birim_fiyat    NUMERIC(12, 2) NOT NULL,
    indirim_tutari NUMERIC(12, 2) NOT NULL DEFAULT 0,
    kdv_tutari     NUMERIC(12, 2) NOT NULL DEFAULT 0,
    satir_tutari   NUMERIC(14, 2) NOT NULL
);

CREATE TABLE IF NOT EXISTS iadeler (
    iade_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    siparis_id         INTEGER NOT NULL REFERENCES siparisler (siparis_id),
    musteri_id         INTEGER NOT NULL REFERENCES musteriler (musteri_id),
    iade_tarihi        DATE NOT NULL,
    neden              TEXT COLLATE "tr-TR-x-icu" NOT NULL,
    durum              TEXT NOT NULL CHECK (durum IN ('onaylandi', 'beklemede', 'reddedildi')),
    toplam_iade_tutari NUMERIC(14, 2) NOT NULL
);

CREATE TABLE IF NOT EXISTS iade_kalemleri (
    iade_kalem_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iade_id       INTEGER NOT NULL REFERENCES iadeler (iade_id),
    urun_id       INTEGER NOT NULL REFERENCES urunler (urun_id),
    ret_qty       INTEGER NOT NULL CHECK (ret_qty > 0),
    iade_tutari   NUMERIC(14, 2) NOT NULL,
    aciklama      TEXT COLLATE "tr-TR-x-icu" NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS faturalar (
    fatura_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    siparis_id      INTEGER NOT NULL REFERENCES siparisler (siparis_id),
    musteri_id      INTEGER NOT NULL REFERENCES musteriler (musteri_id),
    fatura_no       TEXT NOT NULL UNIQUE,
    fatura_tarihi   DATE NOT NULL,
    vade_tarihi     DATE NOT NULL,
    kdv_haric_tutar NUMERIC(14, 2) NOT NULL,
    kdv_tutari      NUMERIC(14, 2) NOT NULL,
    genel_toplam    NUMERIC(14, 2) NOT NULL,
    odenen_tutar    NUMERIC(14, 2) NOT NULL DEFAULT 0,
    durum           TEXT NOT NULL CHECK (durum IN ('odendi', 'kismi_odendi', 'odenmedi', 'vadesi_gecmis', 'iptal')),
    tenant_id       TEXT NOT NULL DEFAULT 't-kurum'
);

CREATE TABLE IF NOT EXISTS odemeler (
    odeme_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fatura_id     INTEGER NOT NULL REFERENCES faturalar (fatura_id),
    musteri_id    INTEGER NOT NULL REFERENCES musteriler (musteri_id),
    odeme_tarihi  DATE NOT NULL,
    tutar         NUMERIC(14, 2) NOT NULL,
    odeme_yontemi TEXT COLLATE "tr-TR-x-icu" NOT NULL,
    iban          TEXT NOT NULL, -- Hassas / sahte (TR00...)
    durum         TEXT NOT NULL CHECK (durum IN ('basarili', 'beklemede', 'iptal'))
);

CREATE TABLE IF NOT EXISTS satis_hedefleri (
    hedef_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bayi_id           INTEGER NOT NULL REFERENCES bayiler (bayi_id),
    yil               INTEGER NOT NULL,
    ay                INTEGER NOT NULL CHECK (ay BETWEEN 1 AND 12),
    hedef_tutar       NUMERIC(14, 2) NOT NULL,
    gerceklesen_tutar NUMERIC(14, 2) NOT NULL
);

-- RBAC hassas tablo: standart analist rolüne kapalıdır.
CREATE TABLE IF NOT EXISTS maaslar (
    maas_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calisan_id INTEGER NOT NULL REFERENCES calisanlar (calisan_id),
    donem_yil  INTEGER NOT NULL,
    donem_ay   INTEGER NOT NULL CHECK (donem_ay BETWEEN 1 AND 12),
    brut_maas  NUMERIC(12, 2) NOT NULL,
    net_maas   NUMERIC(12, 2) NOT NULL,
    prim       NUMERIC(12, 2) NOT NULL DEFAULT 0,
    iban       TEXT NOT NULL -- Hassas / sahte (TR00...)
);

CREATE TABLE IF NOT EXISTS masraflar (
    masraf_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departman_id  INTEGER NOT NULL REFERENCES departmanlar (departman_id),
    bayi_id       INTEGER NOT NULL REFERENCES bayiler (bayi_id),
    masraf_tarihi DATE NOT NULL,
    kategori      TEXT COLLATE "tr-TR-x-icu" NOT NULL,
    tutar         NUMERIC(12, 2) NOT NULL,
    aciklama      TEXT COLLATE "tr-TR-x-icu" NOT NULL,
    onay_durumu   TEXT NOT NULL CHECK (onay_durumu IN ('onaylandi', 'beklemede', 'reddedildi'))
);

CREATE TABLE IF NOT EXISTS tedarikciler (
    tedarikci_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tedarikci_adi TEXT COLLATE "tr-TR-x-icu" NOT NULL,
    sehir         TEXT COLLATE "tr-TR-x-icu" NOT NULL,
    vergi_no      TEXT NOT NULL,
    telefon       TEXT NOT NULL,
    eposta        TEXT NOT NULL,
    vade_gun      INTEGER NOT NULL DEFAULT 30
);

CREATE TABLE IF NOT EXISTS satin_alma_siparisleri (
    satin_alma_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tedarikci_id   INTEGER NOT NULL REFERENCES tedarikciler (tedarikci_id),
    depo_id        INTEGER NOT NULL REFERENCES depolar (depo_id),
    urun_id        INTEGER NOT NULL REFERENCES urunler (urun_id),
    siparis_tarihi DATE NOT NULL,
    teslim_tarihi  DATE,
    miktar         INTEGER NOT NULL CHECK (miktar > 0),
    birim_maliyet  NUMERIC(12, 2) NOT NULL,
    toplam_tutar   NUMERIC(14, 2) NOT NULL,
    durum          TEXT NOT NULL CHECK (durum IN ('teslim_alindi', 'yolda', 'onay_bekliyor', 'iptal'))
);

CREATE TABLE IF NOT EXISTS sevkiyatlar (
    sevkiyat_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    siparis_id    INTEGER NOT NULL REFERENCES siparisler (siparis_id),
    depo_id       INTEGER NOT NULL REFERENCES depolar (depo_id),
    kargo_firmasi TEXT COLLATE "tr-TR-x-icu" NOT NULL,
    takip_no      TEXT NOT NULL UNIQUE,
    cikis_tarihi  DATE NOT NULL,
    teslim_tarihi DATE,
    durum         TEXT NOT NULL CHECK (durum IN ('teslim_edildi', 'dagitimda', 'hazirlaniyor', 'iade_dondu'))
);

CREATE TABLE IF NOT EXISTS destek_talepleri (
    talep_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    musteri_id     INTEGER NOT NULL REFERENCES musteriler (musteri_id),
    siparis_id     INTEGER REFERENCES siparisler (siparis_id),
    calisan_id     INTEGER NOT NULL REFERENCES calisanlar (calisan_id),
    konu           TEXT COLLATE "tr-TR-x-icu" NOT NULL,
    oncelik        TEXT NOT NULL CHECK (oncelik IN ('dusuk', 'orta', 'yuksek', 'kritik')),
    durum          TEXT NOT NULL CHECK (durum IN ('acik', 'inceleniyor', 'cozuldu', 'kapali')),
    acilis_tarihi  DATE NOT NULL,
    kapanis_tarihi DATE
);

-- Çapraz dilli şema eşleme tabloları (Cross-lingual English-abbreviated tables/columns)
CREATE TABLE IF NOT EXISTS cust_loyalty (
    loyalty_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cust_id     INTEGER NOT NULL UNIQUE REFERENCES musteriler (musteri_id),
    tier_code   TEXT NOT NULL CHECK (tier_code IN ('BRONZE', 'SILVER', 'GOLD', 'PLATINUM')),
    pts_bal     INTEGER NOT NULL DEFAULT 0,
    enrolled_dt DATE NOT NULL,
    last_upd_dt DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS inv_ledger (
    ledger_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cust_id   INTEGER NOT NULL REFERENCES musteriler (musteri_id),
    inv_id    INTEGER NOT NULL REFERENCES faturalar (fatura_id),
    prod_id   INTEGER NOT NULL REFERENCES urunler (urun_id),
    inv_amt   NUMERIC(14, 2) NOT NULL,
    ret_qty   INTEGER NOT NULL DEFAULT 0,
    net_bal   NUMERIC(14, 2) NOT NULL,
    tx_dt     DATE NOT NULL,
    curr_code TEXT NOT NULL DEFAULT 'TRY'
);

CREATE TABLE IF NOT EXISTS prod_pricing_hist (
    hist_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prod_id    INTEGER NOT NULL REFERENCES urunler (urun_id),
    old_prc    NUMERIC(12, 2) NOT NULL,
    new_prc    NUMERIC(12, 2) NOT NULL,
    chg_dt     DATE NOT NULL,
    chg_reason TEXT COLLATE "tr-TR-x-icu" NOT NULL
);

CREATE TABLE IF NOT EXISTS wh_stock_snap (
    snap_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wh_id        INTEGER NOT NULL REFERENCES depolar (depo_id),
    prod_id      INTEGER NOT NULL REFERENCES urunler (urun_id),
    qty_on_hand  INTEGER NOT NULL,
    qty_reserved INTEGER NOT NULL DEFAULT 0,
    snap_dt      DATE NOT NULL
);

-- Temel performans indeksleri
CREATE INDEX IF NOT EXISTS idx_bayiler_sehir ON bayiler (sehir);
CREATE INDEX IF NOT EXISTS idx_musteriler_sehir ON musteriler (sehir);
CREATE INDEX IF NOT EXISTS idx_siparisler_tarih_durum ON siparisler (siparis_tarihi, durum);
CREATE INDEX IF NOT EXISTS idx_faturalar_vade_durum ON faturalar (vade_tarihi, durum);
CREATE INDEX IF NOT EXISTS idx_inv_ledger_cust_prod ON inv_ledger (cust_id, prod_id);
